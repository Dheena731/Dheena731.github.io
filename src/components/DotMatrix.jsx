const ROWS = 7;
const GAP = 1;

/** LED split-flap display that cycles through `words`. */
export default function DotMatrix({ words, interval = 2600, dot = 5 }) {
  const [i, setI] = useState(0);
  const [phase, setPhase] = useState('in');

  useEffect(() => {
    if (words.length < 2) return;
    const t = setInterval(() => {
      setPhase('out');
      setTimeout(() => {
        setI((n) => (n + 1) % words.length);
        setPhase('in');
      }, 260);
    }, interval);
    return () => clearInterval(t);
  }, [words.length, interval]);

  const word = words[i] ?? '';
  const glyphs = [...word].map((ch) => FONT[ch.toUpperCase()] ?? FONT[' ']);
  const cols = glyphs.reduce((n, g) => n + g[0].length + GAP, -GAP);
  const step = dot + 1.6;

  return (
    <div
      className="panel overflow-hidden px-3 py-2.5"
      style={{ background: 'var(--ink)', borderColor: 'var(--line)' }}
      role="img"
      aria-label={word}
    >
      <svg
        viewBox={`0 0 ${cols * step} ${ROWS * step}`}
        width="100%"
        style={{
          display: 'block',
          opacity: phase === 'in' ? 1 : 0.15,
          transition: 'opacity .26s ease',
        }}
      >
        {glyphs.map((glyph, gi) => {
          const offset = glyphs.slice(0, gi).reduce((n, g) => n + g[0].length + GAP, 0);
          return glyph.map((row, y) =>
            [...row].map((bit, x) => (
              <rect
                key={`${gi}-${y}-${x}`}
                x={(offset + x) * step}
                y={y * step}
                width={dot}
                height={dot}
                rx={0.6}
                fill={bit === '1' ? 'var(--orange)' : 'var(--paper)'}
                opacity={bit === '1' ? 1 : 0.07}
              />
            )),
          );
        })}
      </svg>
    </div>
  );
}
